  String tr(String key, [Map<String, String> values = const {}]) {
    var result = _values[locale.languageCode]?[key] ?? _values['en']![key] ?? key;
    for (final entry in values.entries) {
      result = result.replaceAll('{${entry.key}}', entry.value);
    }
    return result;
  }

  String category(String value) => tr(value);

  String month(int month) => tr(const [
        '',
        'monthJanuary',
        'monthFebruary',
        'monthMarch',
        'monthApril',
        'monthMay',
        'monthJune',
        'monthJuly',
        'monthAugust',
        'monthSeptember',
        'monthOctober',
        'monthNovember',
        'monthDecember',
      ][month]);

